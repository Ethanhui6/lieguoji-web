import {test,expect} from '@playwright/test';
import {create} from './fms-culture47-fixture';

test('地图外观: live province edges, city labels, relief and political opacity persist and reset',async({page},info)=>{
  test.setTimeout(180000);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const createWorld=async()=>{await page.goto('/?fms=1&fmsDiagnostics=1');await page.getByLabel('整图种子',{exact:true}).fill('421730');await page.getByRole('button',{name:'预览整张地图',exact:true}).click();await page.getByRole('button',{name:'确认整图',exact:true}).click({timeout:90000});await page.getByRole('button',{name:'保存地图',exact:true}).click();await page.getByRole('button',{name:'进入世界 →',exact:true}).click();await create(page);};
  await createWorld();
  const map=page.getByTestId('culture47-map');
  const zoomForBorders=async()=>{await expect(map).toHaveAttribute('data-state-lines',/rendered-voronoi-edges/);for(let i=0;i<12;i++){const p=JSON.parse((await map.getAttribute('data-projection'))!);if(p.zoom>4)return;await page.getByRole('button',{name:'放大地图',exact:true}).click();}throw Error('省界近景缩放未到达');};
  await zoomForBorders();
  const lines=async()=>JSON.parse((await map.getAttribute('data-state-lines'))!);
  const cityNames=async()=>JSON.parse((await map.getAttribute('data-cities'))!).filter((c:{label:boolean})=>c.label).length;
  await expect.poll(cityNames).toBeGreaterThan(0);
  await expect.poll(async()=>(await lines()).drawnProvinceEdges).toBeGreaterThan(0);
  const initial=await lines();
  const open=async()=>{await page.getByRole('button',{name:/菜单/}).first().click();await page.getByRole('button',{name:/^地图外观/}).click();};
  await open();
  const display=page.getByRole('dialog').getByLabel('地图外观');
  await display.getByLabel('行省边界颜色',{exact:true}).fill('#ff3300');
  await expect.poll(async()=>(await lines()).provinceBorderColor).toBe('#ff3300');
  await display.getByRole('checkbox',{name:'显示行省边界',exact:true}).uncheck();
  await expect.poll(async()=>(await lines()).drawnProvinceEdges).toBe(0);
  // State outlines keep the same exact topology when internal province ink is hidden.
  expect(await lines()).toMatchObject({geometry:'rendered-voronoi-edges',lines:initial.lines,points:initial.points});
  await display.getByRole('checkbox',{name:'显示城市名',exact:true}).uncheck();
  await expect.poll(cityNames).toBe(0);
  await display.getByRole('checkbox',{name:'植被图标',exact:true}).uncheck();
  await display.getByRole('slider',{name:'国家颜色浓度'}).fill('0.25');
  await expect.poll(async()=>JSON.parse((await map.getAttribute('data-terrain-display'))!)).toEqual({biomeIcons:false,stateOpacity:.25});
  await page.getByRole('button',{name:'关闭菜单选项',exact:true}).click();
  const changed=await page.screenshot({animations:'disabled'});await page.screenshot({path:info.outputPath('appearance-custom.png'),animations:'disabled'});
  await page.reload();await create(page);
  await zoomForBorders();
  await expect.poll(async()=>(await lines()).drawnProvinceEdges).toBe(0);
  await expect.poll(cityNames).toBe(0);
  await expect.poll(async()=>JSON.parse((await map.getAttribute('data-terrain-display'))!)).toEqual({biomeIcons:false,stateOpacity:.25});
  const beforeReset=await map.getAttribute('data-projection');
  await open();await expect(display.getByLabel('行省边界颜色',{exact:true})).toHaveValue('#ff3300');
  await display.getByRole('button',{name:'恢复默认',exact:true}).click();
  await expect.poll(cityNames).toBeGreaterThan(0);
  await expect.poll(async()=>(await lines()).drawnProvinceEdges).toBeGreaterThan(0);
  await expect.poll(async()=>JSON.parse((await map.getAttribute('data-terrain-display'))!)).toEqual({biomeIcons:true,stateOpacity:.78});
  await page.getByRole('button',{name:'关闭菜单选项',exact:true}).click();
  await expect(map).toHaveAttribute('data-projection',beforeReset!);
  expect((await page.screenshot({animations:'disabled'})).equals(changed)).toBe(false);
  await page.screenshot({path:info.outputPath('appearance-default.png'),animations:'disabled'});
  expect(errors).toEqual([]);
});
