import {test,expect} from '@playwright/test';
import {create} from './fms-culture47-fixture';

test('portrait details leave the map available and expand for long country records',async({page},info)=>{
 test.setTimeout(120000);
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/?fms=1');
 await page.getByRole('button',{name:'生成大陆',exact:true}).click();
 await page.getByRole('button',{name:'确认原作地形',exact:true}).click({timeout:90000});
 await page.getByRole('button',{name:'保存地图',exact:true}).click();
 await page.getByRole('button',{name:'进入世界 →',exact:true}).click();
 await create(page);
 const map=page.getByTestId('culture47-map'),app=page.getByTestId('culture47-app');
 const news=page.getByRole('button',{name:'顶部事件'});
 await expect(news).toBeVisible();
 const newsHeight=(await news.boundingBox())!.height;
 expect(newsHeight).toBeLessThanOrEqual(46);
 await page.locator('.c47-nations button').first().click();
 const panel=page.getByRole('complementary',{name:'文化与国家详情'});
 const collapsed=await panel.boundingBox(),viewport=page.viewportSize();
 expect(collapsed).not.toBeNull();expect(viewport).not.toBeNull();
 expect(collapsed!.height).toBeLessThan(viewport!.height*.39);
 expect(collapsed!.y).toBeGreaterThan(viewport!.height*.42);
 await page.screenshot({path:info.outputPath('portrait-details-map-visible.png')});
 const cities=JSON.parse((await map.getAttribute('data-cities'))!) as {id:string;name:string;x:number;y:number}[];
 const visible=cities.find(c=>c.x>32&&c.x<viewport!.width-32&&c.y>210&&c.y<collapsed!.y-20);
 expect(visible).toBeDefined();
 await map.click({position:{x:visible!.x,y:visible!.y}});
 await expect(panel).toContainText(visible!.name);
 await expect.poll(async()=>{
   const citySection=await panel.locator('.c47-cities-section').boundingBox(),sheet=await panel.boundingBox();
   return citySection!==null&&sheet!==null&&citySection.y<sheet.y+sheet.height;
 }).toBe(true);
 const expand=page.getByRole('button',{name:'展开详情面板',exact:true});
 await expand.click();
 const expanded=await panel.boundingBox();expect(expanded).not.toBeNull();
 expect(expanded!.height).toBeGreaterThan(collapsed!.height+120);
 await page.screenshot({path:info.outputPath('portrait-details-expanded.png')});
 await page.getByRole('button',{name:'收起为半屏',exact:true}).click();
 expect((await panel.boundingBox())!.height).toBeLessThan(viewport!.height*.39);
 await panel.evaluate(element=>{element.scrollTop=element.scrollHeight;});
 await page.locator('.c47-nations button').nth(1).click();
 await expect.poll(()=>panel.evaluate(element=>element.scrollTop)).toBe(0);
 await page.setViewportSize({width:375,height:667});
 await page.getByRole('button',{name:'展开详情面板',exact:true}).click();
 const shortPanel=(await panel.boundingBox())!,nationBar=(await page.locator('.c47-nations').boundingBox())!;
 expect(shortPanel.y).toBeGreaterThan(nationBar.y+nationBar.height+5);
 await page.getByRole('button',{name:'收起为半屏',exact:true}).click();
 await page.getByRole('button',{name:'继续时间',exact:true}).click();
 await expect.poll(async()=>Number(await app.getAttribute('data-tick')),{timeout:90000}).toBeGreaterThan(0);
 await page.getByRole('button',{name:'暂停时间',exact:true}).click();
 expect(errors).toEqual([]);
 await info.attach('portrait-panel',{body:JSON.stringify({collapsedHeight:collapsed!.height,expandedHeight:expanded!.height,exposedMapTop:collapsed!.y,shortViewportExpandedTop:shortPanel.y,shortViewportNationBarBottom:nationBar.y+nationBar.height,newsHeight,pickedCity:visible!.id,tick:await app.getAttribute('data-tick'),errors,physicalIphone:false}),contentType:'application/json'});
});
