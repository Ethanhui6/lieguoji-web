import path from 'node:path';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import { ESLint } from 'eslint';

const root = process.cwd(), stage = path.join(root, '.autopilot/ph06/v4-private-ingress-staging');
const owned = ['src/world/bridge.ts', 'src/world/detail-private-ingress.test.ts'];
const paths = new Map(owned.map(file => [path.resolve(root, file), path.resolve(stage, file)]));
const staged = file => paths.get(path.resolve(file)) ?? file;
const config = ts.readConfigFile(path.join(root, 'tsconfig.json'), ts.sys.readFile), parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
const host = ts.createCompilerHost(parsed.options), originalRead = host.readFile, originalExists = host.fileExists;
host.fileExists = file => originalExists(staged(file)); host.readFile = file => originalRead(staged(file));
host.getSourceFile = (file, languageVersion) => { const source = host.readFile(file); return source === undefined ? undefined : ts.createSourceFile(file, source, languageVersion, true); };
const program = ts.createProgram([...owned.map(file => path.join(root, file)), path.join(root, 'src/vite-env.d.ts')], parsed.options, host);
const diagnostics = ts.getPreEmitDiagnostics(program).map(diagnostic => ({ file: diagnostic.file?.fileName, start: diagnostic.start, code: diagnostic.code, message: ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n') }));
const eslint = new ESLint({ cwd: root }), results = [];
for (const file of owned) results.push(...await eslint.lintText(readFileSync(path.join(stage, file), 'utf8'), { filePath: path.join(root, file) }));
const lint = results.filter(result => result.messages.length).map(result => ({ file: result.filePath, messages: result.messages }));
const report = { checkedAt: new Date().toISOString(), stagingOnly: true, owned, relatedTypeDiagnostics: diagnostics, lint, pass: diagnostics.length === 0 && results.every(result => result.errorCount === 0) };
process.stdout.write(`${JSON.stringify(report, null, 2)}\n`); process.exitCode = report.pass ? 0 : 1;
