import { expect, test } from '@playwright/test';

test('map rainfall is an undoable saved map edit, and world entry states the default-rule boundary', async ({page},info) => {
  test.setTimeout(180000);
  const errors:string[]=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/?fms=1');
  const app=page.getByTestId('fms-app'), canvas=page.getByTestId('fms-canvas');
  const stats=async()=>JSON.parse((await canvas.getAttribute('data-original-editor'))!);
  await page.getByLabel('整图种子',{exact:true}).fill('421730');
  await page.getByRole('button',{name:'预览整张地图',exact:true}).click();
  await page.getByRole('button',{name:'确认整图',exact:true}).click({timeout:90000});
  await page.getByRole('button',{name:'保存地图',exact:true}).click();
  await expect(app).toHaveAttribute('data-dirty','false');
  const revision=Number(await app.getAttribute('data-revision')), land=await app.getAttribute('data-land-cells'), normal=await stats();
  expect(normal.rainfall).toBe(80);
  await page.getByRole('button',{name:'绘图设置',exact:true}).click();
  await page.getByLabel('地图降水',{exact:true}).selectOption('20');
  await expect.poll(async()=>(await stats()).rainfall).toBe(20);
  const dry=await stats();
  expect(dry.rivers).toBeLessThan(normal.rivers);
  await expect(app).toHaveAttribute('data-revision',String(revision+1));
  await expect(app).toHaveAttribute('data-document-version','2');
  await expect(app).toHaveAttribute('data-land-cells',land!);
  await expect(app).toHaveAttribute('data-dirty','true');
  await page.getByRole('button',{name:'收起绘图设置'}).click();
  await page.screenshot({path:info.outputPath('dry-map.png'),fullPage:true});
  // Appearance is display-only and must not recompute the climate.
  await page.getByLabel('地图外观',{exact:true}).selectOption('source');
  await page.getByLabel('地图外观',{exact:true}).selectOption('paper');
  expect((await stats()).climateBuilds).toBe(dry.climateBuilds);
  await page.getByRole('button',{name:'撤销',exact:true}).click();
  await expect.poll(async()=>(await stats()).rainfall).toBe(80);
  expect((await stats()).rivers).toBe(normal.rivers);
  await page.getByRole('button',{name:'重做',exact:true}).click();
  await expect.poll(async()=>(await stats()).rainfall).toBe(20);
  expect((await stats()).rivers).toBe(dry.rivers);
  await page.getByRole('button',{name:'保存地图',exact:true}).click();
  await expect(app).toHaveAttribute('data-dirty','false');
  await page.reload();
  await expect(app).toHaveAttribute('data-land-cells',land!);
  await expect(app).toHaveAttribute('data-document-version','2');
  await expect.poll(async()=>(await stats()).rainfall,{timeout:30000}).toBe(20);
  expect((await stats()).rivers).toBe(dry.rivers);
  await page.getByRole('button',{name:'绘图设置',exact:true}).click();
  await expect(page.getByLabel('地图降水',{exact:true})).toHaveValue('20');
  await page.getByRole('button',{name:'收起绘图设置'}).click();
  await page.getByRole('button',{name:'进入世界 →',exact:true}).click();
  await expect(page.getByRole('note')).toContainText('地图降水20已随地图保存',{timeout:30000});
  await page.screenshot({path:info.outputPath('world-entry-notice.png')});
  expect(errors).toEqual([]);
  await info.attach('rainfall-counts',{body:JSON.stringify({normal,dry,revision}),contentType:'application/json'});
});
